// Writes THIRD_PARTY_NOTICES.md: the third-party software shipped in the installer, with its license.
// Usage: node scripts/third-party-notices.mjs   (run again after a dependency change, before a release)
import { execSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

// Production dependency tree, as installed (what electron-builder packs into the app).
const tree = JSON.parse(execSync('npm ls --omit=dev --all --json', { encoding: 'utf8', maxBuffer: 64e6 }))
// Left out of the installer by electron-builder.yml: not shipped, so not listed.
const NOT_SHIPPED = new Set([
  '@node-llama-cpp/win-arm64',
  '@node-llama-cpp/win-x64-cuda',
  '@node-llama-cpp/win-x64-cuda-ext',
])
const packages = new Map()
const visit = (deps) => {
  for (const [name, info] of Object.entries(deps ?? {})) {
    if (!info.version || info.missing || NOT_SHIPPED.has(name)) continue
    const key = `${name}@${info.version}`
    if (!packages.has(key)) {
      let license = 'see package'
      try {
        const meta = JSON.parse(readFileSync(join('node_modules', name, 'package.json'), 'utf8'))
        license = typeof meta.license === 'string' ? meta.license : (meta.license?.type ?? license)
      } catch {
        // nested copy: the license of the top-level copy is not necessarily the same, keep "see package"
      }
      packages.set(key, { name, version: info.version, license })
    }
    visit(info.dependencies)
  }
}
visit(tree.dependencies)

const byLicense = new Map()
for (const p of [...packages.values()].sort((a, b) => a.name.localeCompare(b.name))) {
  const list = byLicense.get(p.license) ?? []
  list.push(`- ${p.name} ${p.version}`)
  byLicense.set(p.license, list)
}

const text = `# Third-party notices

Re:CV is released under the [MIT License](LICENSE). It ships the third-party software below, each under its own
license; the full license texts are in each package's \`LICENSE\` file inside the installed application
(\`resources/app.asar\` and \`resources/app.asar.unpacked/node_modules\`).

This file is generated by \`node scripts/third-party-notices.mjs\`.

## Electron and Chromium

Re:CV runs on [Electron](https://www.electronjs.org/) (MIT License), which includes Chromium, Node.js and their own
dependencies. Their notices ship with the application in \`LICENSE.electron.txt\` and \`LICENSES.chromium.html\`, next to
\`ReCV.exe\`.

## llama.cpp

The built-in AI engine is [llama.cpp](https://github.com/ggml-org/llama.cpp) (MIT License, Copyright (c) 2023-2024 The
ggml authors), packaged by [node-llama-cpp](https://github.com/withcatai/node-llama-cpp) (MIT License).

## AI models

The AI models are not included in the installer: Re:CV downloads them on request. The Qwen models are distributed by
their authors under the Apache License 2.0.

## npm packages

${[...byLicense.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([license, list]) => `### ${license}\n\n${list.join('\n')}`)
  .join('\n\n')}
`
writeFileSync('THIRD_PARTY_NOTICES.md', text)
console.log(`THIRD_PARTY_NOTICES.md: ${packages.size} packages, ${byLicense.size} licenses`)
